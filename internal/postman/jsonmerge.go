package postman

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"strings"
)

// rawBodyIndent matches the indentation Postman uses for generated raw bodies.
const rawBodyIndent = "  "

type jsonKind int

const (
	jsonScalar jsonKind = iota
	jsonObject
	jsonArray
)

// jsonNode is a minimal JSON tree that keeps object key order, so merged
// bodies keep the field order of the spec instead of being sorted.
type jsonNode struct {
	kind   jsonKind
	fields []jsonField     // jsonObject
	items  []*jsonNode     // jsonArray
	scalar json.RawMessage // jsonScalar
}

type jsonField struct {
	key   string
	value *jsonNode
}

func (n *jsonNode) field(key string) (*jsonNode, bool) {
	for _, f := range n.fields {
		if f.key == key {
			return f.value, true
		}
	}
	return nil, false
}

// mergeRawBody merges a user-edited raw body (old) with the body generated
// from the spec (new). base is the body generated by the previous sync, or nil
// when unknown. An untouched body (old == base) is replaced by new verbatim.
//
// JSON bodies are merged node by node:
//   - a value the user left untouched since base follows the spec,
//   - an edited value is kept; when it changed kind in the spec (e.g.
//     string → object) the spec wins,
//   - fields only in the spec are added, unless the baseline shows the user
//     deleted them,
//   - fields no longer in the spec are dropped, unless the baseline shows the
//     user added them (without a baseline they are always dropped),
//   - arrays keep the old elements; object elements are merged against the
//     spec's (and baseline's) first element.
//
// If either side is not valid JSON (e.g. it contains unquoted {{variables}}),
// the old body is considered hand-written and kept unchanged.
func mergeRawBody(old string, base *string, new string) string {
	if base != nil && old == *base {
		return new
	}
	if strings.TrimSpace(old) == "" {
		return new
	}
	if old == new {
		return old
	}
	oldNode, err := parseJSON(old)
	if err != nil {
		return old
	}
	newNode, err := parseJSON(new)
	if err != nil {
		return old
	}
	var baseNode *jsonNode
	if base != nil {
		baseNode, _ = parseJSON(*base) // an unparsable baseline is just unknown
	}
	out, err := formatJSON(mergeJSON(oldNode, baseNode, newNode))
	if err != nil {
		return old
	}
	return out
}

// mergeJSON merges old and new JSON nodes; base may be nil when unknown.
func mergeJSON(old, base, new *jsonNode) *jsonNode {
	if base != nil && equalJSON(old, base) {
		return new
	}
	if old.kind != new.kind {
		return new
	}
	if base != nil && base.kind != old.kind {
		base = nil
	}
	switch new.kind {
	case jsonObject:
		return mergeJSONObject(old, base, new)
	case jsonArray:
		if len(new.items) == 0 || new.items[0].kind != jsonObject {
			return old
		}
		template := new.items[0]
		var baseTemplate *jsonNode
		if base != nil && len(base.items) > 0 {
			baseTemplate = base.items[0]
		}
		merged := &jsonNode{kind: jsonArray, items: make([]*jsonNode, 0, len(old.items))}
		for _, item := range old.items {
			merged.items = append(merged.items, mergeJSON(item, baseTemplate, template))
		}
		return merged
	default:
		return old
	}
}

func mergeJSONObject(old, base, new *jsonNode) *jsonNode {
	merged := &jsonNode{kind: jsonObject, fields: make([]jsonField, 0, len(new.fields))}
	baseField := func(key string) (*jsonNode, bool) {
		if base == nil {
			return nil, false
		}
		return base.field(key)
	}

	for _, f := range new.fields {
		ov, inOld := old.field(f.key)
		bv, inBase := baseField(f.key)
		switch {
		case inOld:
			merged.fields = append(merged.fields, jsonField{key: f.key, value: mergeJSON(ov, bv, f.value)})
		case inBase:
			// Generated last time but removed by the user: keep it removed.
		default:
			merged.fields = append(merged.fields, f)
		}
	}

	if base == nil {
		return merged
	}
	for _, f := range old.fields {
		_, inNew := new.field(f.key)
		_, inBase := base.field(f.key)
		if !inNew && !inBase {
			merged.fields = append(merged.fields, f) // added by the user
		}
	}
	return merged
}

func equalJSON(a, b *jsonNode) bool {
	var ba, bb bytes.Buffer
	return writeJSONNode(&ba, a) == nil && writeJSONNode(&bb, b) == nil && bytes.Equal(ba.Bytes(), bb.Bytes())
}

func parseJSON(s string) (*jsonNode, error) {
	dec := json.NewDecoder(strings.NewReader(s))
	dec.UseNumber()
	n, err := decodeJSONNode(dec)
	if err != nil {
		return nil, err
	}
	if _, err := dec.Token(); !errors.Is(err, io.EOF) {
		return nil, errors.New("unexpected data after JSON value")
	}
	return n, nil
}

func decodeJSONNode(dec *json.Decoder) (*jsonNode, error) {
	tok, err := dec.Token()
	if err != nil {
		return nil, err
	}
	delim, isDelim := tok.(json.Delim)
	if !isDelim {
		raw, err := encodeJSONScalar(tok)
		return &jsonNode{kind: jsonScalar, scalar: raw}, err
	}

	switch delim {
	case '{':
		n := &jsonNode{kind: jsonObject}
		for dec.More() {
			keyTok, err := dec.Token()
			if err != nil {
				return nil, err
			}
			key, ok := keyTok.(string)
			if !ok {
				return nil, fmt.Errorf("unexpected object key %v", keyTok)
			}
			value, err := decodeJSONNode(dec)
			if err != nil {
				return nil, err
			}
			n.fields = append(n.fields, jsonField{key: key, value: value})
		}
		_, err := dec.Token() // closing '}'
		return n, err
	case '[':
		n := &jsonNode{kind: jsonArray}
		for dec.More() {
			item, err := decodeJSONNode(dec)
			if err != nil {
				return nil, err
			}
			n.items = append(n.items, item)
		}
		_, err := dec.Token() // closing ']'
		return n, err
	default:
		return nil, fmt.Errorf("unexpected delimiter %q", delim)
	}
}

// encodeJSONScalar encodes a decoded token without HTML escaping, so
// placeholders such as "<string>" stay readable.
func encodeJSONScalar(v any) (json.RawMessage, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return bytes.TrimRight(buf.Bytes(), "\n"), nil
}

func formatJSON(n *jsonNode) (string, error) {
	var compact bytes.Buffer
	if err := writeJSONNode(&compact, n); err != nil {
		return "", err
	}
	var out bytes.Buffer
	if err := json.Indent(&out, compact.Bytes(), "", rawBodyIndent); err != nil {
		return "", err
	}
	return out.String(), nil
}

func writeJSONNode(buf *bytes.Buffer, n *jsonNode) error {
	switch n.kind {
	case jsonObject:
		buf.WriteByte('{')
		for i, f := range n.fields {
			if i > 0 {
				buf.WriteByte(',')
			}
			key, err := encodeJSONScalar(f.key)
			if err != nil {
				return err
			}
			buf.Write(key)
			buf.WriteByte(':')
			if err := writeJSONNode(buf, f.value); err != nil {
				return err
			}
		}
		buf.WriteByte('}')
	case jsonArray:
		buf.WriteByte('[')
		for i, item := range n.items {
			if i > 0 {
				buf.WriteByte(',')
			}
			if err := writeJSONNode(buf, item); err != nil {
				return err
			}
		}
		buf.WriteByte(']')
	default:
		buf.Write(n.scalar)
	}
	return nil
}
